import 'package:shared_preferences/shared_preferences.dart';

class LanguageOption {
  final String code;
  final String name;
  final String nativeName;
  final String region;

  const LanguageOption({
    required this.code,
    required this.name,
    required this.nativeName,
    required this.region,
  });
}

