    LanguageOption(code: 'pa', name: 'Punjabi', nativeName: 'ਪੰਜਾਬੀ', region: 'Punjab, Haryana'),
    LanguageOption(code: 'kn', name: 'Kannada', nativeName: 'ಕನ್ನಡ', region: 'Karnataka'),
  ];

  String get currentLanguageName {
    for (final l in supportedLanguages) {
      if (l.code == _currentLang) return l.nativeName;
    }
    return 'English';
  }

  bool isSupported(String code) {
    return supportedLanguages.any((l) => l.code == code);
  }

  LanguageProvider() {
    _loadFromPrefs();
  }

  Future<void> _loadFromPrefs() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString('app_lang');
      if (saved != null && isSupported(saved)) {
        _currentLang = saved;
        notifyListeners();
      }
    } catch (_) {}
  }

  Future<void> setLanguage(String lang) async {
    if (lang != _currentLang && isSupported(lang)) {
      _currentLang = lang;
      notifyListeners();
      try {
        final prefs = await SharedPreferences.getInstance();
        await prefs.setString('app_lang', lang);
      } catch (_) {}
    }
  }

